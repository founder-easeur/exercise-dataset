"""Shared enumerations used across models, pipeline and API."""
from __future__ import annotations

import enum


class StructureType(str, enum.Enum):
    """Kind of anatomical structure. Not everything is a muscle."""
    muscle = "muscle"
    tendon = "tendon"
    ligament = "ligament"
    fascia = "fascia"
    nerve = "nerve"
    joint_capsule = "joint_capsule"


class ExerciseRole(str, enum.Enum):
    """How an exercise relates to a muscle/structure."""
    primary = "primary"
    secondary = "secondary"
    stabilizer = "stabilizer"
    stretch_target = "stretch_target"


class RegionRole(str, enum.Enum):
    primary = "primary"
    secondary = "secondary"


class Difficulty(str, enum.Enum):
    beginner = "beginner"
    intermediate = "intermediate"
    advanced = "advanced"


class ReviewStatus(str, enum.Enum):
    draft = "draft"
    pending_review = "pending_review"
    approved = "approved"
    rejected = "rejected"
    flagged = "flagged"


class DataOrigin(str, enum.Enum):
    """Where a piece of data came from — the core provenance distinction."""
    source_fact = "source_fact"        # extracted verbatim/structured from a source document
    normalized = "normalized"          # derived during normalization (deterministic)
    curated = "curated"                # written/reviewed by the Easeur team (seed dataset)
    ai_inference = "ai_inference"      # generated by an AI model, unverified
    human_reviewed = "human_reviewed"  # confirmed by a human reviewer


class RecordOrigin(str, enum.Enum):
    curated = "curated"        # seeded curated dataset
    aggregated = "aggregated"  # discovered/crawled from external sources


class SourceType(str, enum.Enum):
    government = "government"
    hospital = "hospital"
    university = "university"
    medical_org = "medical_org"
    physio_org = "physio_org"
    academic = "academic"
    reputable_exercise = "reputable_exercise"
    other = "other"


class SourceAuthority(str, enum.Enum):
    high = "high"
    medium = "medium"
    unknown = "unknown"


class LicenseStatus(str, enum.Enum):
    public_domain = "public_domain"
    cc0 = "cc0"
    cc_by = "cc_by"
